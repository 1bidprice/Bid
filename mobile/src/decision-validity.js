const finiteTime = (value) => Number.isFinite(Number(value));

export const DECISION_VALIDITY_VERSION = '2026-09-05.1';

function parseTime(value) {
  if (value === null || value === undefined || value === '') return null;
  const time = new Date(value).getTime();
  return Number.isFinite(time) ? time : null;
}

/**
 * A FINAL action is allowed to surface as a current user action only when all
 * three independent conditions are true:
 * 1. the decision feed itself is fresh;
 * 2. the production evidence/decision system is operational;
 * 3. the action has a valid, non-expired validUntil timestamp.
 *
 * Missing/invalid validity data fails closed. A fresh market quote must never
 * revive an expired decision generated by an older research feed.
 */
export function finalActionValidity(finalAction, options = {}) {
  const now = finiteTime(options.now) ? Number(options.now) : Date.now();
  const feedFresh = options.feedFresh === true;
  const systemReady = options.systemReady === true;
  const isFinal = finalAction?.status === 'FINAL';
  const validUntilMs = parseTime(finalAction?.validUntil);
  const hasVerifiedValidity = validUntilMs !== null;
  const expired = hasVerifiedValidity ? validUntilMs <= now : true;

  let reason = null;
  if (!isFinal) reason = 'NOT_FINAL';
  else if (!feedFresh) reason = 'FEED_NOT_FRESH';
  else if (!systemReady) reason = 'SYSTEM_NOT_READY';
  else if (!hasVerifiedValidity) reason = 'VALID_UNTIL_NOT_VERIFIED';
  else if (expired) reason = 'DECISION_EXPIRED';

  return {
    eligible: reason === null,
    reason,
    expired,
    feedFresh,
    systemReady,
    validUntilMs,
  };
}

export function finalActionIsCurrent(finalAction, options = {}) {
  return finalActionValidity(finalAction, options).eligible;
}
